function openForm(root, scroll=true) {
  root.classList.add('is-form-open');
  history.replaceState(null,'',`${location.pathname}${location.search}#cadastro`);
  if (scroll) requestAnimationFrame(()=>root.querySelector('.step-careers-hero')?.scrollIntoView({behavior:'smooth',block:'start'}));
}

function closeForm(root) {
  root.classList.remove('is-form-open');
  history.replaceState(null,'',`${location.pathname}${location.search}`);
  requestAnimationFrame(()=>root.querySelector('.step-careers-landing')?.scrollIntoView({behavior:'smooth',block:'start'}));
}

function injectStyles(base) {
  if (document.querySelector('link[data-step-careers-landing]')) return;
  const link=document.createElement('link'); link.rel='stylesheet'; link.href=`${base}src/landing.css?v=2`; link.dataset.stepCareersLanding='1'; document.head.appendChild(link);
}

function applyLogo(root, base) {
  const brand=root.querySelector('.step-careers-brand');
  if (!brand) return;
  const src = new URL(`${base}assets/step-logo.svg`, document.baseURI).href;
  brand.innerHTML=`<img class="step-careers-logo" src="${src}" alt="STEP Integrated Solutions" onerror="this.style.display='none';this.parentElement.insertAdjacentHTML('beforeend','<strong style=&quot;font-size:22px;color:#0b2e62&quot;>STEP</strong>')">`;
}

function esc(value='') { return String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); }
