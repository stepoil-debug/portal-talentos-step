const root = document.getElementById('step-careers-root');
if (root) initLanding(root);

function initLanding(root) {
  const locale = root.dataset.locale || detectLocale();
  const base = root.dataset.base || './';
  const copy = landingCopy[locale] || landingCopy.en;
  let attempts = 0;

  const timer = setInterval(() => {
    attempts += 1;
    const shell = root.querySelector('.step-careers-shell');
    const main = root.querySelector('.step-careers-container');
    if (shell && main) {
      clearInterval(timer);
      buildLanding(root, main, base, copy);
    } else if (attempts > 100) {
      clearInterval(timer);
    }
  }, 20);
}

function detectLocale() {
  const language = (navigator.language || 'en').toLowerCase();
  if (language.startsWith('pt-br')) return 'pt-BR';
  if (language.startsWith('pt')) return 'pt-PT';
  if (language.startsWith('es')) return 'es';
  if (language.startsWith('fr')) return 'fr';
  return 'en';
}

